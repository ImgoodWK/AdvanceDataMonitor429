export function isThemeColor(value: string | null | undefined): value is ThemeColor {
  return !!value && (THEME_COLORS as string[]).includes(value);
}

export function resolveThemeColor(value: string | null | undefined): ThemeColor {
  if (isThemeColor(value)) return value;
  if (value && LEGACY_THEME_COLOR_ALIASES[value]) return LEGACY_THEME_COLOR_ALIASES[value];
  return 'dark';
}
