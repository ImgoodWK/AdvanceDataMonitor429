/** Per-widget / resolved chart drawing recipe ids (7 options). */
export type ChartStyle =
  | 'inherit'
  | 'classic'
  | 'viz'
  | 'minimal'
  | 'filled'
  | 'outlined'
  | 'spark';

/** Concrete chart drawing knobs (no data/interaction changes). */
export interface ChartStyleRecipe {
  strokeWidth: number;
  areaOpacity: number;
  /** When false, area polygons are omitted even if areaColor is set. */
  showArea: boolean;
  gridYs: number[];
  gridStrokeWidth: number;
  gridOpacity: number;
  pointRadius: number;
  barTopRadius: number;
  pieRadius: number;
  pieStrokeWidth: number;
  radarFillOpacity: number;
  radarRingScales: number[];
  radarStrokeWidth: number;
}

export interface PageStylePreset {
  id: PageStyle;
  cssVars: Record<string, string>;
  /** antd borderRadius override (before compact layout shrink). */
  borderRadius: number;
  /** Optional UI font-family override for antd token. */
  fontFamily?: string;
  /** Default chartStyle when widget uses inherit. */
  defaultChartStyle: Exclude<ChartStyle, 'inherit'>;
}

