export function isPageStyle(value: string | null | undefined): value is PageStyle {
  return !!value && (PAGE_STYLES as string[]).includes(value);
}

export function isChartStyle(value: string | null | undefined): value is ChartStyle {
  return !!value && (CHART_STYLES as string[]).includes(value);
}

export function resolvePageStyle(value: string | null | undefined): PageStyle {
  return isPageStyle(value) ? value : 'classic';
}

/**
 * Map pageStyle → concrete chart recipe when widget chartStyle is inherit.
 */
export function chartStyleFromPageStyle(pageStyle: PageStyle): Exclude<ChartStyle, 'inherit'> {
  return PAGE_STYLE_PRESETS[pageStyle].defaultChartStyle;
}

export function getChartStyleRecipe(
  chartStyle: Exclude<ChartStyle, 'inherit'>
): ChartStyleRecipe {
  return CHART_STYLE_RECIPES[chartStyle];
}
